-- Class books for every ability and rank a class trainer teaches from level
-- 61 to 80, dropping in Azeroth's top raids. Ritz, 2026-09-24/25: "if we
-- made class abilities that required between levels 61 and 80 learnable
-- from tomes?" / "can we make tomes only drop from Azeroth?" / "For all the
-- abilities" / death knights too ("yeah!") / "Let's use option 1" (the stock
-- class-book way).
--
-- Each book is a copy of the game's own Ahn'Qiraj class book for its class
-- (Tome of Frostbolt XI and its kind): the client's "Learning" spell first,
-- the ability second marked "learn this spell", limited to one class,
-- required level 60. The server teaches it with no script and the client
-- draws the ability's own tooltip. Two limits come from the generated list:
-- the races that may learn it (a few abilities belong to one faction), and a
-- talent the reader must know (higher ranks of a talent ability).
--
-- Drops, each an equal pick among the tier's books:
--   levels 61-70: Ahn'Qiraj 40 about 1.5 books a clear (9 loot bosses);
--                 Ahn'Qiraj 20 a quarter of that per kill; each Emerald
--                 Dragon three, always.
--   levels 71-80: Naxxramas about 1.5 books a clear (15 loot bosses), both
--                 sizes.
--
-- Books are items 1557001-1557999; the two tier pools are reference loot
-- 1557901 (61-70) and 1557902 (71-80). Nothing stock is changed, only
-- added, so each apply first removes what an earlier apply added and the
-- revert removes it all. Database: acore_world_basic. Applied by E037.
-- ============================================================================

