-- ---- 3. the books ---------------------------------------------------------------------------
-- Copy each model row (the extra first column is dropped before the insert,
-- so the rest line up with item_template's own columns), then set what makes
-- each book itself.
DROP TABLE IF EXISTS `tmp_155q_items`;
CREATE TABLE `tmp_155q_items` SELECT b.`item` AS `book`, i.*
FROM `tmp_155q_books` b JOIN `tmp_155q_kinds` k ON k.`class` = b.`class` JOIN `item_template` i ON i.`entry` = k.`model`;
UPDATE `tmp_155q_items` t JOIN `tmp_155q_books` b ON b.`item` = t.`book` JOIN `tmp_155q_kinds` k ON k.`class` = b.`class`
SET t.`entry`          = b.`item`,
    t.`name`           = CONCAT(k.`prefix`, b.`title`),
    t.`description`    = b.`teaches`,
    t.`AllowableClass` = 1 << (b.`class` - 1),
    t.`AllowableRace`  = IF(b.`races` = 0, -1, b.`races`),
    t.`spellid_1`      = 483,                 -- the client's "Learning" spell
    t.`spelltrigger_1` = 0,
    t.`spellid_2`      = b.`taught`,
    t.`spelltrigger_2` = 6,                   -- ITEM_SPELLTRIGGER_LEARN_SPELL_ID
    t.`requiredspell`  = b.`talent`,
    t.`RequiredLevel`  = 60;
ALTER TABLE `tmp_155q_items` DROP COLUMN `book`;
