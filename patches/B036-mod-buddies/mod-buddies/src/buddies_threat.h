/*
 * buddies_threat.h - threat and attention as a buddy works them out (issue
 * 625j, the threat economy); plain arithmetic, apart from the server, so it
 * can be tested on its own (tests/buddy-threat/, scripts/test-buddy-threat).
 *
 * For a general audience: each enemy keeps a list of how much threat each
 * character has built on it; its attention is the one it hits now. The
 * owner, 2026-10-30: "threat is something that has to be managed. This
 * means it doesn't matter generally how much of it there is, but more
 * importantly where is it stored. It's like a worker placement game,
 * except with "threat" and "attention" and such." This file says, the way
 * the server decides it (ThreatManager.cpp, read 2026-10-30), whom an
 * enemy attacks, and what each lever (a taunt, a handing-on, a share cut,
 * leaving the fight, an immunity) does to its list, so a buddy can try a
 * lever in its head before spending it. The levers themselves are read
 * from the game's spell table (BUDDY_THREAT_LEVERS, generated by
 * scripts/generate-ability-data).
 */

#ifndef MOD_BUDDIES_THREAT_H
#define MOD_BUDDIES_THREAT_H

#include "buddies_ability_data.h"
#include "buddies_lockouts.h"

#include <algorithm>
#include <cstring>
#include <limits>
#include <vector>

namespace BuddyThreat
{
    // {{{ Entry
    // One character on an enemy's threat list:
    //   threat  how much it has built (never below 0)
    //   state   2 online; 1 passed over (immune to the enemy's melee,
    //           confused, or held by a stun that breaks on damage: its threat
    //           kept, threat it makes meanwhile lost); 0 offline (out of the
    //           fight, or unseen: invisible to an enemy that can't see it)
    //   taunt   1 taunting the enemy, 0 not, -1 its taunt turned away
    //   melee   within the enemy's melee reach
    struct Entry { double threat; int state; int taunt; bool melee; };
    // }}}

    // {{{ Below
    // The server's order (ThreatManager::CompareReferencesLT): whether `a`
    // comes below `b`, `a`'s threat weighed by `weight`. Online before
    // passed over before offline; then a taunt before none before a turned
    // taunt; then the threat.
    inline bool Below(Entry const& a, Entry const& b, double weight = 1.0)
    {
        if (a.state != b.state) return a.state < b.state;
        if (a.taunt != b.taunt) return a.taunt < b.taunt;
        return a.threat * weight < b.threat;
    }
    // }}}

    // {{{ Attention
    // Whom the enemy attacks (an index into its list; -1 no one), as the
    // server's ReselectVictim decides, given whom it attacks now (`current`,
    // -1 no one). The top of the list, unless it is offline (then no one).
    // The current one is kept unless the top beats it by 10% from within
    // melee reach or 30% from anywhere; and when the top is at range under
    // 30%, the highest one within melee reach that beats it by 10% takes it.
    // (A fixated enemy, a boss's own choice, is the server's and is left out.)
    inline int Attention(std::vector<Entry> const& list, int current)
    {
        if (list.empty()) return -1;
        std::vector<int> order(list.size());
        for (size_t i = 0; i < list.size(); ++i) order[i] = static_cast<int>(i);
        std::stable_sort(order.begin(), order.end(), [&](int x, int y) { return Below(list[y], list[x]); });   // highest first
        int top = order[0];
        if (list[top].state == 0) return -1;
        if (current < 0 || list[current].state == 0 || top == current) return top;
        Entry const& now = list[current];
        if (!Below(now, list[top], 1.1)) return current;
        if (Below(now, list[top], 1.3)) return top;
        if (list[top].melee) return top;
        for (int i : order)
        {
            if (i == current) return current;
            if (!Below(now, list[i], 1.1)) return current;
            if (list[i].melee) return i;
        }
        return current;
    }
    // }}}

    // {{{ the levers' effects on one enemy's list
    // Taunt: the taunter's threat raised to the top's, and its taunt on
    // (SPELL_EFFECT_ATTACK_ME, ThreatManager::MatchUnitThreatToHighestThreat;
    // the aura's taunt state), so it comes first while the taunt lasts.
    inline void Taunt(std::vector<Entry>& list, size_t who)
    {
        double top = 0.0;
        for (size_t i = 0; i < list.size(); ++i)
            if (i != who && list[i].state > 0) top = std::max(top, list[i].threat);
        list[who].threat = std::max(list[who].threat, top);
        list[who].taunt  = 1;
    }
    // Share: threat changed by a percent (Soulshatter -50, Hand of
    // Salvation's -2 a tick), never below 0.
    inline void Share(std::vector<Entry>& list, size_t who, double percent)
    {
        list[who].threat = std::max(0.0, list[who].threat * (1.0 + percent / 100.0));
    }
    // Hand: threat that `from` would make handed to `to` instead
    // (Misdirection, Tricks of the Trade): `amount` of threat goes to `to`.
    inline void Hand(std::vector<Entry>& list, size_t to, double amount)
    {
        if (list[to].state == 2) list[to].threat += amount;               // a passed-over or offline one gains nothing
    }
    // Leave: out of the fight (Feign Death, Vanish, Invisibility to an enemy
    // that can't see it): offline, its threat dropped.
    inline void Leave(std::vector<Entry>& list, size_t who)
    {
        list[who].state  = 0;
        list[who].threat = 0.0;
    }
    // Immune: passed over while immune (Divine Shield; Hand of Protection
    // against a physical attacker; Ice Block), its threat kept. Not a wipe:
    // when it ends and the character next makes threat, it is online again
    // with what it kept (Comeback).
    inline void Immune(std::vector<Entry>& list, size_t who)
    {
        if (list[who].state == 2) list[who].state = 1;
    }
    inline void Comeback(std::vector<Entry>& list, size_t who)
    {
        if (list[who].state == 1) list[who].state = 2;
    }
    // }}}

    // {{{ LeverOf
    // An ability's row in the generated lever table (nullptr: it moves no
    // threat or attention), by class and its name in lower case.
    inline BuddyThreatLeverRow const* LeverOf(uint8_t cls, char const* name)
    {
        for (BuddyThreatLeverRow const& r : BUDDY_THREAT_LEVERS)
            if (r.cls == cls && std::strcmp(r.name, name) == 0) return &r;
        return nullptr;
    }
    inline bool Does(BuddyThreatLeverRow const* row, char const* kind)
    {
        return row && BuddyLockout::Lists(row->kinds, kind);
    }
    // }}}
}

#endif
